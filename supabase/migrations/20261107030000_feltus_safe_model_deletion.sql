-- FELTUS: app-scoped, confirmed model deletion.
-- Physical and registry changes run in one transaction. Never use CASCADE.

CREATE OR REPLACE FUNCTION public.feltus_model_deletion_impact(
    p_app_id UUID,
    p_model_id UUID
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_owner UUID := auth.uid();
    v_model RECORD;
    v_table_oid OID;
    v_fields JSONB;
    v_inbound JSONB;
    v_outbound JSONB;
    v_foreign_keys JSONB;
    v_database_objects JSONB;
    v_dependent_models JSONB;
    v_blockers JSONB := '[]'::JSONB;
    v_field_count INTEGER;
    v_relationship_count INTEGER;
    v_foreign_key_count INTEGER;
    v_database_object_count INTEGER;
    v_registry_mismatch BOOLEAN;
    v_row_count BIGINT;
BEGIN
    IF v_owner IS NULL THEN
        RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
    END IF;

    SELECT m.id, m.app_id, m.owner_id, m.logical_name, m.physical_table_name
      INTO v_model
      FROM public.feltus_models AS m
      JOIN public.feltus_applications AS a
        ON a.id = m.app_id
       AND a.owner_id = v_owner
     WHERE m.id = p_model_id
       AND m.app_id = p_app_id
       AND m.owner_id = v_owner;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Application or model unavailable to current identity' USING ERRCODE = '42501';
    END IF;

    IF v_model.logical_name IN (
        'assets', 'user_assets', 'feltus_applications', 'feltus_models', 'feltus_model_columns'
    ) THEN
        RAISE EXCEPTION 'Platform-managed models cannot be removed through app data management' USING ERRCODE = '42501';
    END IF;

    -- Only accept a table name generated by FELTUS for this exact registry row.
    -- This protects platform tables and blocks stale or tampered mappings.
    IF v_model.logical_name !~ '^[a-z][a-z0-9_]{0,39}$'
       OR v_model.physical_table_name IS DISTINCT FROM
          ('fm_' || substring(replace(v_model.id::TEXT, '-', '') FROM 1 FOR 8) || '_' || v_model.logical_name)
    THEN
        RAISE EXCEPTION 'Registered model does not map to its FELTUS-owned table' USING ERRCODE = '42501';
    END IF;

    SELECT c.oid
      INTO v_table_oid
      FROM pg_class AS c
      JOIN pg_namespace AS n ON n.oid = c.relnamespace
     WHERE n.nspname = 'public'
       AND c.relname = v_model.physical_table_name
       AND c.relkind = 'r';
    IF v_table_oid IS NULL THEN
        RAISE EXCEPTION 'Registered model table is missing or is not a regular table' USING ERRCODE = '42P01';
    END IF;

    IF EXISTS (
        SELECT 1
          FROM public.feltus_model_columns AS c
         WHERE c.model_id = p_model_id
           AND c.owner_id <> v_owner
    ) THEN
        RAISE EXCEPTION 'Model field metadata is not owned by the current identity' USING ERRCODE = '42501';
    END IF;

    SELECT COUNT(*)::INTEGER,
           COALESCE(jsonb_agg(jsonb_build_object(
               'id', c.id,
               'name', c.column_name,
               'data_type', c.data_type,
               'nullable', c.is_nullable,
               'ordinal_position', c.ordinal_position
           ) ORDER BY c.ordinal_position), '[]'::JSONB)
      INTO v_field_count, v_fields
      FROM public.feltus_model_columns AS c
     WHERE c.model_id = p_model_id
       AND c.owner_id = v_owner;

    EXECUTE format('SELECT count(*) FROM public.%I', v_model.physical_table_name)
       INTO v_row_count;

    SELECT COUNT(*)::INTEGER,
           COALESCE(jsonb_agg(jsonb_build_object(
               'id', r.id,
               'source_model_id', r.source_model_id,
               'source_model', src.logical_name,
               'source_field', r.source_column,
               'target_model_id', r.target_model_id,
               'target_model', dst.logical_name,
               'target_field', r.target_column,
               'constraint_name', r.constraint_name
           ) ORDER BY r.created_at, r.id) FILTER (
               WHERE r.target_model_id = p_model_id AND r.app_id = p_app_id AND r.owner_id = v_owner
           ), '[]'::JSONB),
           COALESCE(jsonb_agg(jsonb_build_object(
               'id', r.id,
               'source_model_id', r.source_model_id,
               'source_model', src.logical_name,
               'source_field', r.source_column,
               'target_model_id', r.target_model_id,
               'target_model', dst.logical_name,
               'target_field', r.target_column,
               'constraint_name', r.constraint_name
           ) ORDER BY r.created_at, r.id) FILTER (
               WHERE r.source_model_id = p_model_id AND r.app_id = p_app_id AND r.owner_id = v_owner
           ), '[]'::JSONB)
      INTO v_relationship_count, v_inbound, v_outbound
      FROM public.feltus_model_relationships AS r
      LEFT JOIN public.feltus_models AS src ON src.id = r.source_model_id
      LEFT JOIN public.feltus_models AS dst ON dst.id = r.target_model_id
     WHERE r.source_model_id = p_model_id OR r.target_model_id = p_model_id;

    SELECT EXISTS (
        SELECT 1
          FROM public.feltus_model_relationships AS r
         WHERE (r.source_model_id = p_model_id OR r.target_model_id = p_model_id)
           AND (r.app_id <> p_app_id OR r.owner_id <> v_owner)
    ) INTO v_registry_mismatch;

    SELECT COUNT(*)::INTEGER,
           COALESCE(jsonb_agg(jsonb_build_object(
               'constraint_name', c.conname,
               'source_table', src.relname,
               'target_table', dst.relname,
               'direction', CASE WHEN c.conrelid = v_table_oid THEN 'outbound' ELSE 'inbound' END,
               'source_columns', ARRAY(
                   SELECT a.attname
                     FROM unnest(c.conkey) WITH ORDINALITY AS key(attnum, position)
                     JOIN pg_attribute AS a ON a.attrelid = c.conrelid AND a.attnum = key.attnum
                    ORDER BY key.position
               ),
               'target_columns', ARRAY(
                   SELECT a.attname
                     FROM unnest(c.confkey) WITH ORDINALITY AS key(attnum, position)
                     JOIN pg_attribute AS a ON a.attrelid = c.confrelid AND a.attnum = key.attnum
                    ORDER BY key.position
               ),
               'registered', EXISTS (
                   SELECT 1
                     FROM public.feltus_model_relationships AS r
                     JOIN public.feltus_models AS source_model
                       ON source_model.id = r.source_model_id
                      AND source_model.app_id = p_app_id
                      AND source_model.owner_id = v_owner
                     JOIN public.feltus_models AS target_model
                       ON target_model.id = r.target_model_id
                      AND target_model.app_id = p_app_id
                      AND target_model.owner_id = v_owner
                    WHERE r.app_id = p_app_id
                      AND r.owner_id = v_owner
                      AND r.constraint_name = c.conname
                      AND source_model.physical_table_name = src.relname
                      AND target_model.physical_table_name = dst.relname
                      AND cardinality(c.conkey) = 1
                      AND cardinality(c.confkey) = 1
                      AND r.source_column = (
                          SELECT a.attname FROM pg_attribute AS a
                           WHERE a.attrelid = c.conrelid AND a.attnum = c.conkey[1]
                      )
                      AND r.target_column = (
                          SELECT a.attname FROM pg_attribute AS a
                           WHERE a.attrelid = c.confrelid AND a.attnum = c.confkey[1]
                      )
               )
           ) ORDER BY c.conname), '[]'::JSONB)
      INTO v_foreign_key_count, v_foreign_keys
      FROM pg_constraint AS c
      JOIN pg_class AS src ON src.oid = c.conrelid
      JOIN pg_class AS dst ON dst.oid = c.confrelid
     WHERE c.contype = 'f'
       AND (c.conrelid = v_table_oid OR c.confrelid = v_table_oid);

    SELECT COALESCE(jsonb_agg(jsonb_build_object(
               'model_id', dependency.model_id,
               'model_name', dependency.model_name,
               'direction', dependency.direction
           ) ORDER BY dependency.direction, dependency.model_name), '[]'::JSONB)
      INTO v_dependent_models
      FROM (
          SELECT DISTINCT
                 CASE WHEN r.source_model_id = p_model_id THEN dst.id ELSE src.id END AS model_id,
                 CASE WHEN r.source_model_id = p_model_id THEN dst.logical_name ELSE src.logical_name END AS model_name,
                 CASE WHEN r.target_model_id = p_model_id THEN 'inbound' ELSE 'outbound' END AS direction
            FROM public.feltus_model_relationships AS r
            LEFT JOIN public.feltus_models AS src ON src.id = r.source_model_id
            LEFT JOIN public.feltus_models AS dst ON dst.id = r.target_model_id
           WHERE (r.source_model_id = p_model_id OR r.target_model_id = p_model_id)
             AND r.app_id = p_app_id
             AND r.owner_id = v_owner
             AND r.source_model_id <> r.target_model_id
          UNION
          SELECT DISTINCT
                 CASE WHEN c.conrelid = v_table_oid THEN target_model.id ELSE source_model.id END AS model_id,
                 CASE WHEN c.conrelid = v_table_oid THEN target_model.logical_name ELSE source_model.logical_name END AS model_name,
                 CASE WHEN c.confrelid = v_table_oid THEN 'inbound' ELSE 'outbound' END AS direction
            FROM pg_constraint AS c
            JOIN pg_class AS source_table ON source_table.oid = c.conrelid
            JOIN pg_class AS target_table ON target_table.oid = c.confrelid
            LEFT JOIN public.feltus_models AS source_model
              ON source_model.physical_table_name = source_table.relname
             AND source_model.app_id = p_app_id
             AND source_model.owner_id = v_owner
            LEFT JOIN public.feltus_models AS target_model
              ON target_model.physical_table_name = target_table.relname
             AND target_model.app_id = p_app_id
             AND target_model.owner_id = v_owner
           WHERE c.contype = 'f'
             AND (c.conrelid = v_table_oid OR c.confrelid = v_table_oid)
             AND CASE WHEN c.conrelid = v_table_oid THEN target_model.id ELSE source_model.id END IS NOT NULL
             AND (source_model.id IS DISTINCT FROM p_model_id OR target_model.id IS DISTINCT FROM p_model_id)
      ) AS dependency;

    -- PostgreSQL tracks view/rule and routine dependencies here. Foreign keys
    -- are reported separately above. Attached indexes/policies are internal
    -- to the managed table and are not blockers for dropping that table.
    SELECT COALESCE(jsonb_agg(jsonb_build_object(
               'object_type', dependency.object_type,
               'description', dependency.description
           ) ORDER BY dependency.object_type, dependency.description), '[]'::JSONB)
      INTO v_database_objects
      FROM (
          SELECT DISTINCT
                 CASE
                   WHEN d.classid = 'pg_rewrite'::REGCLASS THEN 'view_or_rule'
                   WHEN d.classid = 'pg_proc'::REGCLASS THEN 'routine'
                   ELSE 'database_object'
                 END AS object_type,
                 pg_describe_object(d.classid, d.objid, d.objsubid) AS description
            FROM pg_depend AS d
           WHERE d.refclassid = 'pg_class'::REGCLASS
             AND d.refobjid = v_table_oid
             AND d.deptype = 'n'
             AND d.classid IN ('pg_rewrite'::REGCLASS, 'pg_proc'::REGCLASS)
      ) AS dependency;
    v_database_object_count := jsonb_array_length(v_database_objects);

    IF v_relationship_count > 0 THEN
        v_blockers := v_blockers || jsonb_build_array(jsonb_build_object(
            'kind', 'relationships', 'count', v_relationship_count,
            'message', 'Remove the linked relationships first.'
        ));
    END IF;
    IF v_foreign_key_count > 0 THEN
        v_blockers := v_blockers || jsonb_build_array(jsonb_build_object(
            'kind', 'foreign_keys', 'count', v_foreign_key_count,
            'message', 'A database link still uses this category.'
        ));
    END IF;
    IF v_database_object_count > 0 THEN
        v_blockers := v_blockers || jsonb_build_array(jsonb_build_object(
            'kind', 'database_objects', 'count', v_database_object_count,
            'message', 'A database object still depends on this category.'
        ));
    END IF;
    IF v_registry_mismatch THEN
        v_blockers := v_blockers || jsonb_build_array(jsonb_build_object(
            'kind', 'registry_mismatch', 'count', 1,
            'message', 'The category has relationship metadata outside this application.'
        ));
    END IF;

    RETURN jsonb_build_object(
        'app_id', p_app_id,
        'model_id', p_model_id,
        'model_name', v_model.logical_name,
        'physical_table', v_model.physical_table_name,
        'registered_fields', v_fields,
        'field_count', v_field_count,
        'row_count', v_row_count,
        'inbound_relationships', v_inbound,
        'outbound_relationships', v_outbound,
        'foreign_key_constraints', v_foreign_keys,
        'dependent_models', v_dependent_models,
        'dependent_database_objects', v_database_objects,
        'registry_mismatch', v_registry_mismatch,
        'can_delete', jsonb_array_length(v_blockers) = 0,
        'blockers', v_blockers,
        'canonical_state_impact', jsonb_build_object(
            'model_removed_from_current_state', TRUE,
            'saved_blueprints_mutated', FALSE
        )
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.feltus_delete_model(
    p_app_id UUID,
    p_model_id UUID,
    p_confirm BOOLEAN
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_owner UUID := auth.uid();
    v_model RECORD;
    v_table_oid OID;
    v_impact JSONB;
    v_deleted INTEGER;
BEGIN
    IF v_owner IS NULL THEN
        RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
    END IF;
    IF p_confirm IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION 'Explicit confirmation is required' USING ERRCODE = '22023';
    END IF;

    SELECT m.id, m.app_id, m.owner_id, m.logical_name, m.physical_table_name
      INTO v_model
      FROM public.feltus_models AS m
      JOIN public.feltus_applications AS a
        ON a.id = m.app_id
       AND a.owner_id = v_owner
     WHERE m.id = p_model_id
       AND m.app_id = p_app_id
       AND m.owner_id = v_owner
     FOR UPDATE OF m;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Application or model unavailable to current identity' USING ERRCODE = '42501';
    END IF;

    IF v_model.logical_name IN (
        'assets', 'user_assets', 'feltus_applications', 'feltus_models', 'feltus_model_columns'
    ) THEN
        RAISE EXCEPTION 'Platform-managed models cannot be removed through app data management' USING ERRCODE = '42501';
    END IF;

    IF v_model.logical_name !~ '^[a-z][a-z0-9_]{0,39}$'
       OR v_model.physical_table_name IS DISTINCT FROM
          ('fm_' || substring(replace(v_model.id::TEXT, '-', '') FROM 1 FOR 8) || '_' || v_model.logical_name)
    THEN
        RAISE EXCEPTION 'Registered model does not map to its FELTUS-owned table' USING ERRCODE = '42501';
    END IF;

    SELECT c.oid INTO v_table_oid
      FROM pg_class AS c
      JOIN pg_namespace AS n ON n.oid = c.relnamespace
     WHERE n.nspname = 'public'
       AND c.relname = v_model.physical_table_name
       AND c.relkind = 'r';
    IF v_table_oid IS NULL THEN
        RAISE EXCEPTION 'Registered model table is missing or is not a regular table' USING ERRCODE = '42P01';
    END IF;

    -- Serialize relationship writes and table DDL while the authoritative
    -- impact is rechecked. Concurrent FK creation either finishes first and
    -- blocks deletion, or waits and fails after the table has been removed.
    LOCK TABLE public.feltus_model_relationships IN SHARE ROW EXCLUSIVE MODE;
    EXECUTE format('LOCK TABLE public.%I IN ACCESS EXCLUSIVE MODE', v_model.physical_table_name);
    v_impact := public.feltus_model_deletion_impact(p_app_id, p_model_id);
    IF NOT COALESCE((v_impact ->> 'can_delete')::BOOLEAN, FALSE) THEN
        RAISE EXCEPTION 'This category still has relationship or database dependencies' USING ERRCODE = '23503';
    END IF;

    -- No CASCADE: PostgreSQL rejects any dependency missed by the preview and
    -- rolls this function's registry changes back with the DDL statement.
    EXECUTE format('DROP TABLE public.%I', v_model.physical_table_name);

    DELETE FROM public.feltus_models
     WHERE id = p_model_id
       AND app_id = p_app_id
       AND owner_id = v_owner;
    GET DIAGNOSTICS v_deleted = ROW_COUNT;
    IF v_deleted <> 1 THEN
        RAISE EXCEPTION 'Model registry did not match the physical table' USING ERRCODE = '40001';
    END IF;

    RETURN jsonb_build_object(
        'deleted', TRUE,
        'app_id', p_app_id,
        'model_id', p_model_id,
        'model_name', v_model.logical_name,
        'deleted_fields', COALESCE(jsonb_array_length(v_impact -> 'registered_fields'), 0),
        'deleted_rows', COALESCE((v_impact ->> 'row_count')::BIGINT, 0),
        'impact', v_impact
    );
END;
$$;

REVOKE ALL ON FUNCTION public.feltus_model_deletion_impact(UUID, UUID) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.feltus_delete_model(UUID, UUID, BOOLEAN) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.feltus_model_deletion_impact(UUID, UUID) TO authenticated;
GRANT EXECUTE ON FUNCTION public.feltus_delete_model(UUID, UUID, BOOLEAN) TO authenticated;

NOTIFY pgrst, 'reload schema';
